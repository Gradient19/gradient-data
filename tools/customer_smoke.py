def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha256(path):
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def download(tag, name, destination, limit):
    url = ("https://github.com/Gradient19/gradient-data/releases/download/"
           + quote(tag, safe="") + "/" + quote(name, safe=""))
    request = Request(url, headers={"User-Agent": "gradient-data-customer-smoke/1"})
    total = 0
    with urlopen(request, timeout=60) as response, destination.open("xb") as output:
        require(response.status == 200, f"download failed: HTTP {response.status}")
        while True:
            block = response.read(1024 * 1024)
            if not block:
                break
            total += len(block)
            require(total <= limit, f"download exceeds {limit} bytes: {name}")
            output.write(block)
    require(total > 0, f"empty download: {name}")


def check_sidecar(sidecar, archive):
    text = sidecar.read_text("ascii")
    match = re.fullmatch(r"([0-9a-f]{64})(?:  " + re.escape(ASSET) + r")?\r?\n?", text)
    require(match is not None, "invalid release ZIP checksum sidecar")
    require(match.group(1) == ZIP_SHA256, "release ZIP checksum differs from pinned digest")
    require(archive.stat().st_size == ZIP_LIMIT, "release ZIP size differs from pinned size")
    require(sha256(archive) == ZIP_SHA256, "whole release ZIP checksum mismatch")


def check_zip(zip_path):
    require(zip_path.stat().st_size == ZIP_LIMIT, "release ZIP size differs from pinned size")
    with zipfile.ZipFile(zip_path) as archive:
        entries = archive.infolist()
        names = [entry.filename for entry in entries]
        require(len(entries) == len(PACKAGE_FILES), "release ZIP member count mismatch")
        require(set(names) == PACKAGE_FILES and len(set(names)) == len(names),
                "release ZIP exact file roster mismatch")
        require(len({name.casefold() for name in names}) == len(names),
                "release ZIP has case-colliding paths")
        total = 0
        for entry in entries:
            name = entry.filename
            require(name == Path(name).as_posix() and not name.startswith("/")
                    and "\\" not in name and ":" not in name
                    and all(part not in ("", ".", "..") for part in name.split("/")),
                    f"unsafe ZIP path: {name!r}")
            kind = stat.S_IFMT(entry.external_attr >> 16)
            require(kind in (0, stat.S_IFREG) and not entry.is_dir(),
                    f"nonregular ZIP member: {name}")
            require(not entry.flag_bits & 1, f"encrypted ZIP member: {name}")
            require(entry.compress_type in (zipfile.ZIP_STORED, zipfile.ZIP_DEFLATED),
                    f"unsupported ZIP compression: {name}")
            require(entry.file_size <= EXPANDED_LIMIT, f"oversized ZIP member: {name}")
            total += entry.file_size
            require(total <= EXPANDED_LIMIT, "ZIP expansion limit exceeded")
    print("Whole ZIP digest, exact 82-file roster and expansion bounds PASS")


def extract_verified_zip(zip_path, root):
    # root is an empty directory created exclusively by TemporaryDirectory.
    require(not any(root.iterdir()), "extraction directory is not empty")
    with zipfile.ZipFile(zip_path) as archive:
        for entry in archive.infolist():
            target = root / entry.filename
            target.parent.mkdir(parents=True, exist_ok=True)
            with archive.open(entry) as source, target.open("xb") as output:
                shutil.copyfileobj(source, output, 1024 * 1024)
            require(target.stat().st_size == entry.file_size,
                    f"short ZIP member: {entry.filename}")
    if sys.platform == "linux":
        for command in ("uacd", "uacd-gui"):
            (root / "linux-x86_64" / command).chmod(0o755)
    verify_bundle(root)


def expected_dirs(files):
    return {"/".join(name.split("/")[:i]) for name in files
            for i in range(1, len(name.split("/")))}


def verify_bundle(root, installed=False):
    require(root.is_dir() and not root.is_symlink(), "bundle is not an ordinary directory")
    files, dirs = set(), set()
    for base, subdirs, filenames in os.walk(root, followlinks=False):
        for name in subdirs + filenames:
            item = Path(base) / name
            relative = item.relative_to(root).as_posix()
            mode = item.lstat().st_mode
            if stat.S_ISDIR(mode):
                dirs.add(relative)
            elif stat.S_ISREG(mode):
                files.add(relative)
            else:
                raise ValueError(f"nonregular package entry: {relative}")
    expected_files = PACKAGE_FILES | ({"INSTALL_RECEIPT"} if installed else set())
    require(files == expected_files and dirs == expected_dirs(PACKAGE_FILES),
            "package file or directory roster mismatch")
    manifest = (root / "SHA256SUMS").read_bytes()
    expected_manifest = "".join(
        f"{sha256(root / name)}  {name}\n" for name in sorted(PAYLOAD)
    ).encode("ascii")
    require(manifest == expected_manifest, "package SHA256SUMS or payload checksum mismatch")
    if installed:
        receipt = (f"Gradient Data {VERSION}\n" + hashlib.sha256(manifest).hexdigest()
                   + "\n").encode("ascii")
        require((root / "INSTALL_RECEIPT").read_bytes() == receipt,
                "installed bundle receipt mismatch")
    print("Installed" if installed else "Extracted", "public manifest and exact roster PASS")


def run(*command, env=None):
    result = subprocess.run([str(item) for item in command], env=env,
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
                            encoding="utf-8", errors="strict", timeout=180)
    if result.returncode:
        raise RuntimeError(f"command failed ({result.returncode}): {command!r}\n"
                           f"stdout: {result.stdout[-3000:]}\nstderr: {result.stderr[-3000:]}")
    return result


def clean_runtime_environment(bundle, environment):
    env = environment.copy()
    env.pop("LD_LIBRARY_PATH", None)
    if sys.platform == "win32":
        def in_bundle(text):
            try:
                path = Path(text).resolve()
                return path == bundle or bundle in path.parents
            except (OSError, ValueError):
                return False
        env["PATH"] = os.pathsep.join(part for part in env.get("PATH", "").split(os.pathsep)
                                      if part and not in_bundle(part))
    return env


def generated_input():
    # Deterministic non-power-of-two skew, with no private corpus or fixture.
    state = 0x48723995afcb02d1
    thresholds = (52, 92, 123, 150, 173, 192, 207, 219, 229, 237,
                  243, 247, 250, 252, 254, 255)
    raw = bytearray()
    for _ in range(300_003):
        state ^= (state << 13) & ((1 << 64) - 1)
        state ^= state >> 7
        state ^= (state << 17) & ((1 << 64) - 1)
        value = (state >> 24) & 255
        raw.append(next(i for i, limit in enumerate(thresholds) if value <= limit))
    return bytes(raw)


def exercise_folder_inputs(cli, work, runtime):
    """Small public examples: generated bytes, names and empty directory entries."""
    source = work / "example folder"
    source.mkdir()
    (source / "empty directory").mkdir()
    (source / "notes").mkdir()
    member_source = source / "café.dat"
    member_bytes = bytes(range(256)) * 24 + b"Public example bytes with CRLF.\r\n"
    relative_files = {"café.dat": member_bytes, "empty.dat": b"",
                      "notes/readme.txt": b"Generated public consumer example.\n"}
    for name, content in relative_files.items():
        (source / name).write_bytes(content)
    extra = work / "selected.txt"
    extra.write_bytes(b"A separately selected file.\n")
    source_hashes = {name: sha256(source / name) for name in relative_files}
    extra_hash = sha256(extra)
    member = source.name + "/café.dat"
    directories = {source.name, source.name + "/empty directory", source.name + "/notes"}
    folder = work / "folder.uacd"
    multiple = work / "multiple.uacd"
    run(cli, "pack", source, folder, "--profile", "fast", "--block-size", "64KiB", env=runtime)
    run(cli, "pack-many", multiple, source, extra, "--profile", "fast",
        "--block-size", "64KiB", env=runtime)

    def rejected(*arguments):
        result = subprocess.run([str(cli), *map(str, arguments)], env=runtime,
                                capture_output=True, timeout=180)
        require(result.returncode != 0, "folder operation unexpectedly accepted a protected destination or limit")

    for archive, additional in ((folder, {}), (multiple, {extra.name: extra.read_bytes()})):
        with archive.open("rb") as stream:
            require(stream.read(8) == b"UACD0004", "folder archive version mismatch")
        files = {source.name + "/" + name: content for name, content in relative_files.items()}
        files.update(additional)
        listing = json.loads(run(cli, "list", archive, env=runtime).stdout)
        require({entry["path"] for entry in listing["entries"]} == set(files) | directories,
                "folder or selected-root names mismatch")
        info = json.loads(run(cli, "info", archive, env=runtime).stdout)
        require(info["version"] == 4 and info["raw_bytes"] == sum(map(len, files.values()))
                and info["archive_bytes"] == archive.stat().st_size,
                "folder dimensions mismatch")
        run(cli, "verify", archive, env=runtime)
        destination = work / (archive.stem + "-restored")
        run(cli, "unpack", archive, destination, env=runtime)
        for name, content in files.items():
            require((destination / name).read_bytes() == content, "folder whole-file byte mismatch")
        for name in directories:
            require((destination / name).is_dir(), "folder directory entry missing")
        rejected("unpack", archive, destination)
        for name, content in files.items():
            require((destination / name).read_bytes() == content, "existing output tree was changed")
        existing_empty = work / (archive.stem + "-existing-empty")
        existing_empty.mkdir()
        rejected("unpack", archive, existing_empty)
        require(not any(existing_empty.iterdir()), "existing empty output directory was changed")
        selected = work / (archive.stem + "-member.dat")
        run(cli, "extract", archive, member, selected, env=runtime)
        require(selected.read_bytes() == member_bytes, "selected member byte mismatch")
        rejected("extract", archive, member, selected)
        require(selected.read_bytes() == member_bytes, "existing selected member was changed")
        segment = work / (archive.stem + "-range.dat")
        run(cli, "range", archive, "11", "257", segment, "--file", member, env=runtime)
        require(segment.read_bytes() == member_bytes[11:268], "selected member range byte mismatch")
        blocked = work / (archive.stem + "-limited")
        rejected("unpack", archive, blocked, "--max-output", info["raw_bytes"] - 1)
        require(not blocked.exists(), "admission refusal published an output")
        rejected("list", archive, "--max-index", info["index_bytes"] - 1)
        rejected("list", archive, "--max-entries", info["entries"] - 1)
        before = sha256(archive)
        rejected("pack", source, archive, "--profile", "fast")
        require(sha256(archive) == before, "folder pack replaced an existing archive")
    require(source_hashes == {name: sha256(source / name) for name in relative_files}
            and sha256(extra) == extra_hash, "generated source files changed")
    require(not any(item.name.startswith(".uacd.partial-") for item in work.iterdir()),
            "folder operation left partial staging")
    print("Folder and multiple-root CLI roundtrip/member/range/no-overwrite/admission PASS")
    return multiple, member, member_source


def exercise_workers(cli, source, data, work, runtime):
    """Actual installed process quota and two-block ordered byte parity."""
    archives = []
    for workers in (1, 2):
        archive = work / f"worker-{workers}.uacd"
        result = run(cli, "pack", source, archive, "--profile", "fast",
                     "--block-size", "64KiB", "--workers", workers,
                     "--memory-budget", "1GiB", env=runtime)
        policy = "windows-committed" if sys.platform == "win32" else "linux-address-space"
        require("memory_policy=" + policy in result.stderr,
                "installed CLI did not report its actual quota policy")
        restored = work / f"worker-{workers}.restored"
        run(cli, "unpack", archive, restored, env=runtime)
        require(restored.read_bytes() == data, "installed worker reconstruction mismatch")
        archives.append(archive)
    require(sha256(archives[0]) == sha256(archives[1]), "installed workers changed archive bytes")
    for index, flags in enumerate((("--workers", "3"), ("--workers", "2", "--memory-budget", "1"))):
        rejected = work / f"worker-rejected-{index}.uacd"
        before = set(work.iterdir())
        result = subprocess.run([str(cli), "pack", str(source), str(rejected), *flags],
                                env=runtime, capture_output=True, timeout=180)
        require(result.returncode != 0 and not rejected.exists() and set(work.iterdir()) == before,
                "invalid workers/quota created output or staging")
    require(source.read_bytes() == data, "worker smoke modified source")
    print("Installed 1/2 worker exact bytes, OS quota reporting and early refusal PASS")


def exercise_runtime_reader(executable, archive, member, source, runtime):
    """C11/shared or C++17/static; identical returned windows, unmanaged cache."""
    raw = source.read_bytes()
    n = min(len(raw), 4096)
    expected = [(0, n), ((len(raw) - n) // 2, n), (len(raw) - n, n)]
    for mode, args in (("archive", [archive, member]), ("loose", [source])):
        result = run(executable, mode, *args, env=runtime)
        value = json.loads(result.stdout)
        require(value.get("schema") == "uacd-runtime-reader-v1" and value.get("status") == 0
                and value.get("logical_bytes") == len(raw), "runtime reader dimensions/status")
        require(value.get("cache_state") == "unmanaged" and value.get("full_verify_called") is False
                and value.get("unpack_called") is False, "runtime reader changed service")
        require(len(value.get("windows", [])) == len(expected), "runtime reader missing windows")
        for window, (offset, length) in zip(value["windows"], expected):
            require(window.get("status") == 0 and window.get("offset") == offset
                    and window.get("requested_bytes") == length and window.get("returned_bytes") == length
                    and window.get("sha256") == hashlib.sha256(raw[offset:offset + length]).hexdigest(),
                    "runtime reader returned different bytes")
    print("Installed bounded runtime reader archive/loose window hashes PASS")


def exercise_gui(gui, runtime):
    """Minimal native companion serve/auth gate; session details stay in memory."""
    try:
        version = subprocess.run([str(gui), "--version"], env=runtime, capture_output=True,
                                 timeout=180)
    except OSError:
        raise RuntimeError("GUI companion version check could not start") from None
    except subprocess.TimeoutExpired:
        raise RuntimeError("GUI companion version check did not finish") from None
    require(version.returncode == 0 and version.stdout.strip() == f"gradient-data {VERSION}".encode(),
            "GUI companion version differs from release")
    try:
        process = subprocess.Popen([str(gui), "--no-browser"], env=runtime,
                                   stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    except OSError:
        raise RuntimeError("GUI companion could not start") from None
    startup = queue.Queue(maxsize=1)
    def read_startup():
        try:
            line = process.stdout.readline(512)
        except (OSError, UnicodeError, ValueError):
            line = ""
        startup.put(line)
    reader = threading.Thread(target=read_startup, daemon=True)
    reader.start()
    try:
        try:
            line = startup.get(timeout=30).strip()
        except queue.Empty:
            raise RuntimeError("GUI startup response missing") from None
        require(line.startswith("UACD_GUI_URL="), "GUI startup response missing")
        try:
            endpoint = urlsplit(line.split("=", 1)[1])
            port = endpoint.port
        except ValueError:
            raise RuntimeError("GUI startup endpoint invalid") from None
        require(endpoint.scheme == "http" and endpoint.hostname == "127.0.0.1"
                and port is not None and 0 < port < 65536
                and endpoint.netloc == f"127.0.0.1:{port}" and endpoint.path == "/"
                and not endpoint.query and re.fullmatch(r"[0-9a-f]{64}", endpoint.fragment),
                "GUI startup endpoint invalid")
        origin = "http://" + endpoint.netloc

        def request(method, route, expected, headers=None):
            connection = http.client.HTTPConnection("127.0.0.1", port, timeout=15)
            try:
                body = b"{}" if method == "POST" else None
                connection.request(method, route, body=body, headers=headers or {})
                response = connection.getresponse()
                content = response.read(65537)
                require(len(content) <= 65536, "GUI response exceeds consumer bound")
                require(response.status == expected, "GUI serve or authentication status mismatch")
                require(response.getheader("Access-Control-Allow-Origin") is None,
                        "GUI unexpectedly enabled cross-origin access")
                return content
            except (OSError, http.client.HTTPException):
                raise RuntimeError("GUI HTTP request failed") from None
            finally:
                connection.close()

        require(bool(request("GET", "/", 200)), "GUI did not serve its local page")
        unauthenticated = {"Origin": origin, "Content-Type": "application/json"}
        request("POST", "/api/status", 403, unauthenticated)
        authorized = {**unauthenticated, "X-Uacd-Token": endpoint.fragment}
        wrong_origin = {**authorized, "Origin": "https://example.invalid"}
        request("POST", "/api/status", 403, wrong_origin)
        status = json.loads(request("POST", "/api/status", 200, authorized))
        require(status.get("state") == "idle", "GUI authenticated status mismatch")
        request("POST", "/api/shutdown", 200, authorized)
        try:
            require(process.wait(timeout=15) == 0, "GUI shutdown failed")
        except subprocess.TimeoutExpired:
            raise RuntimeError("GUI shutdown did not finish") from None
        print("Native GUI version, local HTTP page, authentication and shutdown PASS")
    finally:
        if process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=15)
            except subprocess.TimeoutExpired:
                process.kill()
                try:
                    process.wait(timeout=15)
                except subprocess.TimeoutExpired:
                    raise RuntimeError("GUI process cleanup did not finish") from None
        reader.join(timeout=1)
        process.stdout.close()
        process.stderr.close()


