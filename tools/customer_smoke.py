"""Download and exercise only the public Gradient Data 0.2.0-rc.2 customer ZIP.

This consumer gate uses generated bytes and the installed CLI/SDK. It does not
build the engine or import a private source tree. The same-release .sha256 is an
integrity check; the release channel, not the checksum itself, identifies origin.
"""

