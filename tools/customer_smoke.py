def install_and_exercise(bundle, scratch):
    environment = os.environ.copy()
    if sys.platform == "win32":
        environment["LOCALAPPDATA"] = str(scratch / "local-app-data")
        prefix = scratch / "local-app-data/Programs/GradientData" / VERSION
        install = ["powershell", "-NoProfile", "-NonInteractive", "-ExecutionPolicy",
                   "Bypass", "-File", str(bundle / "install.ps1")]
        uninstall = ["powershell", "-NoProfile", "-NonInteractive", "-ExecutionPolicy",
                     "Bypass", "-File", str(bundle / "uninstall.ps1")]
    elif sys.platform == "linux":
        environment["XDG_DATA_HOME"] = str(scratch / "xdg-data")
        environment["XDG_BIN_HOME"] = str(scratch / "xdg-bin")
        prefix = scratch / "xdg-data/gradient-data" / VERSION
        install = ["sh", str(bundle / "install.sh")]
        uninstall = ["sh", str(bundle / "uninstall.sh")]
    else:
        raise RuntimeError("only Linux and Windows x86-64 runners are supported")
    require(not prefix.exists() and not prefix.is_symlink(), "test installation exists")
    run(*install, env=environment)
    require(prefix.is_dir() and not prefix.is_symlink(), "installer did not create prefix")
    verify_bundle(prefix, installed=True)
    usage = scratch / "usage"
    usage.mkdir()
    exercise_installed(prefix, usage, environment)
    run(*uninstall, env=environment)
    require(not prefix.exists() and not prefix.is_symlink(), "uninstaller left prefix")
    if sys.platform == "linux":
        for command in ("uacd", "uacd-gui"):
            link = scratch / "xdg-bin" / command
            require(not link.exists() and not link.is_symlink(), "uninstaller left its own command link")
    print("isolated user-local install and uninstall PASS")


